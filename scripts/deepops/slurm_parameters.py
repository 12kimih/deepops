#!/usr/bin/env python3
"""Slurm's own parameter tables, pinned: what each of its config files may say.

    scripts/deepops/slurm_parameters.py SOURCE_DIR      write plugins/filter/slurm_parameters.json
    scripts/deepops/slurm_parameters.py SOURCE_DIR --check

SOURCE_DIR is the release's source tree (the slurm_version tarball, or the SchedMD
repository at its tag). Slurm reads each file through an s_p_options_t table: the key,
its type and, for a key it no longer honours, _defunct_option. This copies the tables
roles/slurm renders against (plugins/filter/slurm_conf.py), so a key that is misspelt,
belongs to another file or was retired in this release fails the deploy, not slurmctld:

    slurm.conf          src/common/read_config.c     slurm_conf_options
    slurm.conf node     src/common/read_config.c     _nodename_options (NodeName= lines)
    slurm.conf partition                             _partition_options (PartitionName=)
    cgroup.conf         src/interfaces/cgroup.c      options of _read_slurm_cgroup_conf
    gres.conf           src/interfaces/gres.c        _gres_conf_options
    gres.conf line                                   _gres_options (Name= / NodeName= lines)
    slurmdbd.conf       src/slurmdbd/read_config.c   options of read_slurmdbd_conf

Run it when slurm_version (roles/slurm/defaults) changes; the tests check the pinned
version is that one.
"""

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import cli  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "plugins" / "filter" / "slurm_parameters.json"

# (file, kind): (source file, the line that opens the table)
TABLES = {
    ("slurm.conf", "global"): ("src/common/read_config.c", "s_p_options_t slurm_conf_options[] = {"),
    ("slurm.conf", "node"): ("src/common/read_config.c", "s_p_options_t _nodename_options[] = {"),
    ("slurm.conf", "partition"): ("src/common/read_config.c", "s_p_options_t _partition_options[] = {"),
    ("cgroup.conf", "global"): ("src/interfaces/cgroup.c", "_read_slurm_cgroup_conf(void)"),
    ("gres.conf", "global"): ("src/interfaces/gres.c", "s_p_options_t _gres_conf_options[] = {"),
    ("gres.conf", "line"): ("src/interfaces/gres.c", "s_p_options_t _gres_options[] = {"),
    ("slurmdbd.conf", "global"): ("src/slurmdbd/read_config.c", "read_slurmdbd_conf(void)"),
}
# The key a record line starts with, which its table leaves to the file's own table.
NAMING = {("slurm.conf", "node"): "NodeName", ("slurm.conf", "partition"): "PartitionName",
          ("gres.conf", "line"): "NodeName"}  # fmt: skip
ENTRY = re.compile(
    r'\{\s*(?:\.key\s*=\s*)?"(\w+)"\s*,\s*(?:\.type\s*=\s*)?(S_P_\w+)\s*(?:,\s*(?:\.handler\s*=\s*)?(\w+))?'
)


def table(text, opening):
    """The entries of the first s_p_options_t table at or after OPENING."""
    start = text.index(opening)
    start = text.index("{", text.index("s_p_options_t", start)) + 1
    end = text.index("{NULL}", start)
    out = {}
    for key, kind, handler in ENTRY.findall(text[start:end]):
        out[key] = {"type": kind.removeprefix("S_P_").lower(), "defunct": handler == "_defunct_option"}
    return out


def version(source):
    m = (
        re.search(r"^Version:\s*(\S+)", (source / "META").read_text(), re.M)
        if (source / "META").exists()
        else None
    )
    return m.group(1) if m else None


def build(source, release):
    texts = {}
    found = {}
    for (conf, kind), (path, opening) in TABLES.items():
        text = texts.setdefault(path, (source / path).read_text())
        found.setdefault(conf, {})[kind] = table(text, opening)
        if (conf, kind) in NAMING:
            found[conf][kind][NAMING[conf, kind]] = {"type": "string", "defunct": False}
    return {"_comment": f"Generated by scripts/deepops/slurm_parameters.py from Slurm {release}; do not edit.",
            "version": release, "files": found}  # fmt: skip


def main(argv=None):
    ap = cli.parser(__doc__)
    ap.add_argument("source", type=Path)
    ap.add_argument("--release", help="the release, when SOURCE has no META (a git checkout)")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    release = args.release or version(args.source)
    if not release:
        ap.error("no META in the source tree: give --release")
    text = json.dumps(build(args.source, release), indent=1, sort_keys=True) + "\n"
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(
                f"stale: {OUT.relative_to(ROOT)} (run scripts/deepops/slurm_parameters.py)", file=sys.stderr
            )
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
