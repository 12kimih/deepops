#!/usr/bin/env python3
"""Write roles/prometheus/files/rules/components.yml: each component's playbook as a
series, deepops:component_playbook:info{component, playbook}, so an alert about a
component (or a package a component installed) names the playbook that brings its hosts
level. The rules file is generated from the playbooks; add or move a component's play,
then run this.

A component's playbook is the one play file, outside the two deploys, that applies its
role with its state from the map (deepops_components.<name> | component_phase); every
other managed role's is the one its deepops_managed_roles entry names.

Usage: component_playbooks.py [--check]   (--check reports a stale file and exits 1)
"""

import re
import sys
from pathlib import Path


sys.path.insert(0, str(Path(__file__).resolve().parent))
import cli  # noqa: E402
import repo_files  # noqa: E402
import yaml_load  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
PATH = "roles/prometheus/files/rules/components.yml"
DEPLOYS = ("playbooks/slurm-cluster.yml", "playbooks/k8s-cluster.yml")
APPLIES = re.compile(r"deepops_components\.(\w+)\s*\|\s*component_phase\b")


def registry(root=ROOT):
    return yaml_load.load((root / "roles/deploy_defaults/vars/main.yml").read_text())[
        "deepops_component_registry"
    ]


def playbooks(root=ROOT):
    """{component: playbook}, every component of the registry; ValueError names a
    component with no playbook or with more than one."""
    found = {}
    for path in repo_files.tracked("playbooks", root=root):
        rel = path.relative_to(root).as_posix()
        if path.suffix not in (".yml", ".yaml") or rel in DEPLOYS:
            continue
        for name in set(APPLIES.findall(path.read_text())):
            found.setdefault(name, set()).add(rel)
    names = registry(root)
    bad = {n: sorted(found.get(n, ())) for n in names if len(found.get(n, ())) != 1}
    if bad:
        raise ValueError(
            "each component needs exactly one playbook: "
            + "; ".join(f"{n}: {', '.join(p) or 'none'}" for n, p in sorted(bad.items()))
        )
    out = {n: found[n].pop() for n in sorted(names)}
    # every other managed role: the playbook its entry names (an operation records none)
    for name, entry in managed(root).items():
        if (entry or {}).get("kind") != "operation":
            out[name] = entry["playbook"]
    return dict(sorted(out.items()))


def managed(root=ROOT):
    """deepops_managed_roles: {role: {kind, playbook}} (roles/deploy_defaults/vars/main.yml)."""
    return (
        yaml_load.load((root / "roles/deploy_defaults/vars/main.yml").read_text()).get(
            "deepops_managed_roles"
        )
        or {}
    )


PLAYBOOK_PATH = re.compile(r"playbooks/[\w./-]+\.ya?ml")


def candidates(playbook):
    """Every playbook PLAYBOOK can name: itself, or each path its expression gives (one
    per site setting), for what cannot know the site (the rules file)."""
    return sorted(set(PLAYBOOK_PATH.findall(playbook))) if "{{" in playbook else [playbook]


def render(mapping):
    """The rules file's text, in the style of the hand-written ones beside it."""
    lines = [
        "---",
        "# Generated by scripts/deepops/component_playbooks.py from the playbooks: edit those,",
        "# then run it. Each component's playbook, for the alerts that name it (os-updates.yml).",
        "groups:",
        "  - name: components",
        "    rules:",
    ]
    for name, playbook in sorted(mapping.items()):
        playbook = " or ".join(candidates(playbook))
        lines += [
            "      - record: deepops:component_playbook:info",
            "        expr: vector(1)",
            f"        labels: {{component: {name}, playbook: {playbook}}}",
        ]
    return "\n".join(lines) + "\n"


def main(argv):
    parser = cli.parser(__doc__)
    parser.add_argument(
        "--check", action="store_true", help="report a stale file and exit 1, writing nothing"
    )
    check = parser.parse_args(argv).check
    path = ROOT / PATH
    text = render(playbooks())
    if path.exists() and path.read_text() == text:
        return 0
    if check:
        print(f"stale: {PATH} (run scripts/deepops/component_playbooks.py)")
        return 1
    path.write_text(text)
    print(f"wrote {PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
